#!/usr/bin/env node
/**
 * Build ScriptInstall distributables from runtime + per-app JSON configs.
 *
 * Usage: node tools/build-installer.mjs
 *
 * Outputs:
 *   scripts/dist/ScriptInstall.js          — generic template (empty items)
 *   scripts/dist/install-<name>.js         — one file per scripts/installers/<name>.json
 *   scripts/installers/<name>.install.js   — same as dist copy (for browsing in repo)
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const scriptsDir = path.join(root, "scripts");
const installersDir = path.join(scriptsDir, "installers");
const distDir = path.join(scriptsDir, "dist");
const runtimePath = path.join(scriptsDir, "ScriptInstall.runtime.js");

const INSTALLER_RUNTIME_VERSION = "2.0.0";

const GENERIC_HEADER = `// ScriptInstall.js
//
// Generic Scriptable installer: download a remote .js file, save it as a named
// script in your Scriptable library, optionally run it, and remove this installer.
//
// 1. Edit INSTALLER below (or use a preconfigured install-*.js from scripts/dist/).
// 2. Paste this entire file into Scriptable and run it once.
//
// Version: ${INSTALLER_RUNTIME_VERSION}

// ============================================================
// CONFIGURE YOUR INSTALL
// ============================================================

`;

const EMPTY_INSTALLER = `const INSTALLER = {
  title: "Script Installer",
  version: "${INSTALLER_RUNTIME_VERSION}",
  deleteSelf: true,
  runAfterInstall: true,
  confirmOverwrite: true,
  items: [
    // Example entry:
    // {
    //   scriptName: "MyScript",
    //   label: "My Script",
    //   url: "https://example.com/MyScript.js",
    //   minBytes: 500,
    //   mustContain: "async function main"
    // }
  ]
};

`;

function readRuntime() {
  let runtime = fs.readFileSync(runtimePath, "utf8").trimStart();
  runtime = runtime.replace(
    /^const RUNTIME_VERSION = "[^"]*";/m,
    `const RUNTIME_VERSION = "${INSTALLER_RUNTIME_VERSION}";`
  );
  return runtime;
}

function readDistBundleVersion(distFilename) {
  const distPath = path.join(distDir, distFilename);
  if (!fs.existsSync(distPath)) {
    return null;
  }
  const text = fs.readFileSync(distPath, "utf8");
  const match = text.match(/^\/\/ Version:\s*(.+)$/m);
  return match ? match[1].trim() : null;
}

function distFilenameForItem(item) {
  if (!item.url) {
    return null;
  }
  const match = item.url.match(/\/([^/]+\.js)$/);
  return match ? match[1] : null;
}

function enrichInstaller(installer) {
  const version = installer.version || INSTALLER_RUNTIME_VERSION;
  const enriched = {
    ...installer,
    version
  };

  enriched.items = (installer.items || []).map((item) => {
    const distFile = distFilenameForItem(item);
    const bundleVersion = distFile ? readDistBundleVersion(distFile) : null;
    const next = { ...item };

    if (bundleVersion) {
      next.bundleVersion = bundleVersion;
      const baseName =
        item.scriptName === "SmartTranslatePro"
          ? "SmartTranslate Pro"
          : item.scriptName === "SmartTranslate"
            ? "SmartTranslate"
            : item.scriptName;
      next.label = `${baseName} ${bundleVersion}`;
    }

    return next;
  });

  return enriched;
}

function buildFile(header, installer, runtime) {
  const installerBlock =
    `const INSTALLER = ${JSON.stringify(installer, null, 2)};\n\n` +
    `// ============================================================\n` +
    `// INSTALLER RUNTIME (usually no need to edit below)\n` +
    `// ============================================================\n\n`;
  return `${header}${installerBlock}${runtime}\n`;
}

function buildPreconfiguredHeader(name, installer) {
  const version = installer.version || INSTALLER_RUNTIME_VERSION;
  return `// install-${name}.js
//
// Preconfigured ScriptInstall for ${installer.title}.
// Paste into Scriptable and run ONCE — installs the app, deletes this installer,
// and opens the installed script.
//
// Generated by tools/build-installer.mjs — do not edit by hand.
//
// Installer package: ${version}

`;
}

function main() {
  const runtime = readRuntime();
  fs.mkdirSync(distDir, { recursive: true });

  const genericInstaller = {
    title: "Script Installer",
    version: INSTALLER_RUNTIME_VERSION,
    deleteSelf: true,
    runAfterInstall: true,
    confirmOverwrite: true,
    items: []
  };

  const genericSource = buildFile(GENERIC_HEADER, genericInstaller, runtime);
  fs.writeFileSync(path.join(scriptsDir, "ScriptInstall.js"), genericSource);
  fs.writeFileSync(path.join(distDir, "ScriptInstall.js"), genericSource);
  console.log("Wrote scripts/ScriptInstall.js");
  console.log("Wrote scripts/dist/ScriptInstall.js");

  const configs = fs
    .readdirSync(installersDir)
    .filter((file) => file.endsWith(".json"))
    .sort();

  for (const file of configs) {
    const name = file.replace(/\.json$/, "");
    const raw = JSON.parse(
      fs.readFileSync(path.join(installersDir, file), "utf8")
    );
    const installer = enrichInstaller(raw);
    const header = buildPreconfiguredHeader(name, installer);
    const source = buildFile(header, installer, runtime);
    const distName = `install-${name}.js`;
    const distPath = path.join(distDir, distName);
    const repoPath = path.join(installersDir, `${name}.install.js`);

    fs.writeFileSync(distPath, source);
    fs.writeFileSync(repoPath, source);
    console.log(`Wrote scripts/dist/${distName}`);
    console.log(`Wrote scripts/installers/${name}.install.js`);
  }
}

main();
