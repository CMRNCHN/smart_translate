#!/usr/bin/env node
/**
 * Bundle modular Scriptable sources into single-file standalones.
 * Output: scripts/dist/SmartTranslate.js and scripts/dist/SmartTranslatePro.js
 *
 * Usage: node tools/bundle.mjs
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const scriptsDir = path.join(root, "scripts");
const distDir = path.join(scriptsDir, "dist");

function read(name) {
  return fs.readFileSync(path.join(scriptsDir, name), "utf8");
}

function stripImportModule(source) {
  return source.replace(
    /^\s*(?:let|const)\s+\w+\s*=\s*importModule\([^)]+\);\s*$/gm,
    ""
  );
}

function stripTryImportBlocks(source) {
  // Remove the helpful try/catch importModule bootstrap from entry scripts.
  return source.replace(
    /let Shared;[\s\S]*?if \(modulesLoaded\) \{\s*await main\(\);\s*\}\s*Script\.complete\(\);\s*/m,
    ""
  );
}

function toConstExport(source, constName) {
  let out = stripImportModule(source);
  out = out.replace(
    /module\.exports\s*=\s*\{/,
    `const ${constName} = {`
  );
  return out.trim() + "\n";
}

function stripTopLevelAwaitMain(source) {
  return source
    .replace(/^\s*await main\(\);\s*$/gm, "")
    .replace(/^\s*Script\.complete\(\);\s*$/gm, "");
}

function prepareEntry(source) {
  let out = stripTryImportBlocks(source);
  out = stripImportModule(out);
  out = stripTopLevelAwaitMain(out);
  return out;
}

function bundleV1() {
  const shared = toConstExport(read("SmartTranslateShared.js"), "Shared");
  const conversation = toConstExport(
    read("SmartTranslateConversation.js"),
    "Conversation"
  );
  const entry = prepareEntry(read("SmartTranslate.js"));

  return `// SmartTranslate.js (standalone bundle)
// Generated by tools/bundle.mjs — paste this ONE script into Scriptable.
// Name it anything (e.g. SmartTranslate). No other scripts required.
// Version: 1.0.0-standalone

${shared}

${conversation}

${entry.trim()}

await main();
Script.complete();
`;
}

function bundlePro() {
  const shared = toConstExport(read("SmartTranslateShared.js"), "Shared");
  const conversation = toConstExport(
    read("SmartTranslateConversation.js"),
    "Conversation"
  );
  const proKit = toConstExport(read("SmartTranslateProKit.js"), "Pro");
  const ui = toConstExport(read("SmartTranslateUI.js"), "UI");
  const entry = prepareEntry(read("SmartTranslatePro.js"));

  return `// SmartTranslatePro.js (standalone bundle)
// Generated by tools/bundle.mjs — paste this ONE script into Scriptable.
// Name it anything (e.g. SmartTranslatePro). No other scripts required.
// Version: 1.1.0-pro-standalone

${shared}

${conversation}

${proKit}

${ui}

${entry.trim()}

await main();
Script.complete();
`;
}

fs.mkdirSync(distDir, { recursive: true });
fs.writeFileSync(path.join(distDir, "SmartTranslate.js"), bundleV1());
fs.writeFileSync(path.join(distDir, "SmartTranslatePro.js"), bundlePro());

console.log("Wrote:");
console.log("  scripts/dist/SmartTranslate.js");
console.log("  scripts/dist/SmartTranslatePro.js");
